import json
meta=[('TSLA','Tesla','Tesla (TSLA)','$',1000,'$',2),('BTC','Bitcoin','Bitcoin (BTC-USD)','$',1000,'$',0),
('GOLD','Gold','Gold (futures)','$',1000,'$',0),('SPX','S&P 500','S&P 500 index','$',1000,'',0),('KZT','USD/KZT','USD/KZT exchange rate','₸',100000,'₸',1)]
def build(src,**extra):
    W=json.load(open(src));assets=[]
    for k,l,n,cur,step,pc,pd in meta:
        rows=W[k]
        assets.append(dict(key=k,label=l,name=n,cur=cur,step=step,pcur=pc,pdec=pd,dates=[r[0] for r in rows],prices=[round(r[1],4) for r in rows]))
    return dict(assets=assets,**extra)
t1=open('tpl.html').read().replace('__CFG__',json.dumps(build('win.json',nHist=40,rounds=10),ensure_ascii=False))
t2=open('tpl2.html').read().replace('__CFG__',json.dumps(build('long.json'),ensure_ascii=False))
# slide 4: illustrative two-asset portfolio; 1000 fixed standard-normal pairs, seed 211, made exactly
# mean 0 / var 1 / uncorrelated in-sample (Gram-Schmidt) so the simulated bars match the theory curves
import random,math
random.seed(211)
N=1000
z1=[random.gauss(0,1) for _ in range(N)];z2=[random.gauss(0,1) for _ in range(N)]
def cen(z):m=sum(z)/len(z);return [v-m for v in z]
def nrm(z):s=math.sqrt(sum(v*v for v in z)/(len(z)-1));return [v/s for v in z]
z1=nrm(cen(z1));z2=cen(z2);b=sum(a*c for a,c in zip(z1,z2))/sum(a*a for a in z1);z2=nrm([c-b*a for a,c in zip(z1,z2)])
t3=open('tpl3.html').read().replace('__CFG__',json.dumps(dict(muA=0.1,sdA=2.0,muB=0.4,sdB=3.0,rho=-0.3,z1=[round(v,4) for v in z1],z2=[round(v,4) for v in z2])))
